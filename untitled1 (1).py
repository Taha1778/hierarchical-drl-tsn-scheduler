    params2 = {"W1": actor2.W1, "b1": actor2.b1, "W2": actor2.W2, "b2": actor2.b2,
               "Wmu": actor2.Wmu, "bmu": actor2.bmu, "log_std": actor2.log_std}
    params_c = {"W1": critic.W1, "b1": critic.b1, "W2": critic.W2, "b2": critic.b2,
                "W3": critic.W3, "b3": critic.b3}

    opt1 = Adam(params1, cfg.lr)
    opt2 = Adam(params2, cfg.lr)
    opt_c = Adam(params_c, cfg.lr)

    rng = np.random.RandomState(seed + 1000 + stage_idx * 7)

    best_f1_local = best_f1_so_far
    best_a1, best_a2, best_c = best_actors

    for ep in range(cfg.train_episodes_stage):
        frac = ep / cfg.train_episodes_stage
        entropy_coef = cfg.entropy_coef_start + (cfg.entropy_coef_end - cfg.entropy_coef_start) * frac
        lr_now = cfg.lr * 0.5 * (1 + np.cos(np.pi * frac))
        opt1.lr = lr_now
        opt2.lr = lr_now
        opt_c.lr = lr_now

        states1, states2, actions1, actions2, logps1, logps2, rewards, dones = [], [], [], [], [], [], [], []
        values = []
        for _ in range(cfg.steps_per_episode):
            s1_raw = env.state_level1()
            s2_raw = env.state_level2(env.prev_slack)
            s1 = norm1.normalize(s1_raw)
            s2 = norm2.normalize(s2_raw)
            norm1.update(s1_raw.reshape(1, -1))
            norm2.update(s2_raw.reshape(1, -1))

            a1, a01_1, logp1 = actor1.act(s1, rng)
            a2, a01_2, logp2 = actor2.act(s2, rng)

            route_prob = a01_1.reshape(max_K, 2)[:K, 0]
            gate_priority = a01_1.reshape(max_K, 2)[:K, 1]
            airtime_frac = a01_2.reshape(max_K, 4)[:K, 0]
            order_raw = a01_2.reshape(max_K, 4)[:K, 1]
            power_frac = a01_2.reshape(max_K, 4)[:K, 2]
            retx_frac = a01_2.reshape(max_K, 4)[:K, 3]

            stats = env.step(route_prob, gate_priority, airtime_frac, order_raw, power_frac, retx_frac)

            f2_norm = stats["f2"] / 0.01
            f4_norm = stats["f4"] / 1.0
            reward = cfg.alpha1 * stats["f1"] - cfg.alpha2 * f2_norm - cfg.alpha3 * stats["f3"] - cfg.alpha4 * f4_norm
            reward = np.clip(reward, -50.0, 50.0)

            v = critic.forward(s1, s2)
            states1.append(s1); states2.append(s2)
            actions1.append(a1); actions2.append(a2)
            logps1.append(logp1); logps2.append(logp2)
            rewards.append(reward)
            values.append(v)
            dones.append(False)

        adv1, ret1 = compute_gae(rewards, values, cfg.gamma_discount, cfg.gae_lambda)
        adv2 = adv1
        ret2 = ret1
        adv1 = (adv1 - adv1.mean()) / (adv1.std() + 1e-8)
        adv2 = (adv2 - adv2.mean()) / (adv2.std() + 1e-8)

        data1 = list(zip(states1, actions1, logps1, adv1, ret1))
        data2 = list(zip(states2, actions2, logps2, adv2, ret2))
        indices = np.arange(len(data1))
        batch_size = min(cfg.batch_size, len(data1))

        for _ in range(cfg.minibatch_epochs):
            np.random.shuffle(indices)
            for start in range(0, len(data1), batch_size):
                batch_idx = indices[start:start+batch_size]
                if len(batch_idx) == 0:
                    continue
                gW1 = np.zeros_like(actor1.W1); gb1 = np.zeros_like(actor1.b1)
                gW2 = np.zeros_like(actor1.W2); gb2 = np.zeros_like(actor1.b2)
                gWmu = np.zeros_like(actor1.Wmu); gbmu = np.zeros_like(actor1.bmu)
                g_logstd1 = np.zeros_like(actor1.log_std)
                for i in batch_idx:
                    s = data1[i][0]; a = data1[i][1]; old_logp = data1[i][2]; adv = data1[i][3]
                    h1 = np.tanh(s @ actor1.W1 + actor1.b1)
                    h2 = np.tanh(h1 @ actor1.W2 + actor1.b2)
                    mu = np.tanh(h2 @ actor1.Wmu + actor1.bmu)
                    std = np.exp(actor1.log_std)
                    logp = (-0.5 * ((a - mu) / std) ** 2 - np.log(std) - 0.5 * np.log(2 * np.pi)).sum()
                    ratio = np.exp(logp - old_logp)
                    unclipped = ratio * adv
                    clipped = np.clip(ratio, 1 - cfg.clip_eps, 1 + cfg.clip_eps) * adv
                    obj = np.minimum(unclipped, clipped)
                    if ratio < 1 - cfg.clip_eps or ratio > 1 + cfg.clip_eps:
                        d_obj_d_logp = 0.0
                    else:
                        d_obj_d_logp = adv * ratio
                    dlogp_dmu = (a - mu) / (std ** 2)
                    dlogp_dlogstd = ((a - mu) ** 2 / (std ** 2) - 1.0)
                    g_logstd1 += -d_obj_d_logp * dlogp_dlogstd + entropy_coef * 1.0
                    dmu = -d_obj_d_logp * dlogp_dmu
                    dz_mu = dmu * (1 - mu**2)
                    gWmu += np.outer(h2, dz_mu)
                    gbmu += dz_mu
                    dh2 = dz_mu @ actor1.Wmu.T
                    dz2 = dh2 * (1 - h2**2)
                    gW2 += np.outer(h1, dz2)
                    gb2 += dz2
                    dh1 = dz2 @ actor1.W2.T
                    dz1 = dh1 * (1 - h1**2)
                    gW1 += np.outer(s, dz1)
                    gb1 += dz1
                grads1 = {"W1": gW1/len(batch_idx), "b1": gb1/len(batch_idx),
                          "W2": gW2/len(batch_idx), "b2": gb2/len(batch_idx),
                          "Wmu": gWmu/len(batch_idx), "bmu": gbmu/len(batch_idx),
                          "log_std": g_logstd1/len(batch_idx)}
                norm = np.sqrt(sum((g**2).sum() for g in grads1.values()))
                if norm > 2.0:
                    grads1 = {k: g * 2.0 / (norm + 1e-8) for k, g in grads1.items()}
                updates1 = opt1.step(grads1)
                for k, upd in updates1.items():
                    if k == "log_std":
                        actor1.log_std -= upd
                    else:
                        setattr(actor1, k, getattr(actor1, k) - upd)

                gW1_2 = np.zeros_like(actor2.W1); gb1_2 = np.zeros_like(actor2.b1)
                gW2_2 = np.zeros_like(actor2.W2); gb2_2 = np.zeros_like(actor2.b2)
                gWmu_2 = np.zeros_like(actor2.Wmu); gbmu_2 = np.zeros_like(actor2.bmu)
                g_logstd2 = np.zeros_like(actor2.log_std)
                for i in batch_idx:
                    s = data2[i][0]; a = data2[i][1]; old_logp = data2[i][2]; adv = data2[i][3]
                    h1 = np.tanh(s @ actor2.W1 + actor2.b1)
                    h2 = np.tanh(h1 @ actor2.W2 + actor2.b2)
                    mu = np.tanh(h2 @ actor2.Wmu + actor2.bmu)
                    std = np.exp(actor2.log_std)
                    logp = (-0.5 * ((a - mu) / std) ** 2 - np.log(std) - 0.5 * np.log(2 * np.pi)).sum()
                    ratio = np.exp(logp - old_logp)
                    unclipped = ratio * adv
                    clipped = np.clip(ratio, 1 - cfg.clip_eps, 1 + cfg.clip_eps) * adv
                    obj = np.minimum(unclipped, clipped)
                    if ratio < 1 - cfg.clip_eps or ratio > 1 + cfg.clip_eps:
                        d_obj_d_logp = 0.0
                    else:
                        d_obj_d_logp = adv * ratio
                    dlogp_dmu = (a - mu) / (std ** 2)
                    dlogp_dlogstd = ((a - mu) ** 2 / (std ** 2) - 1.0)
                    g_logstd2 += -d_obj_d_logp * dlogp_dlogstd + entropy_coef * 1.0
                    dmu = -d_obj_d_logp * dlogp_dmu
                    dz_mu = dmu * (1 - mu**2)
                    gWmu_2 += np.outer(h2, dz_mu)
                    gbmu_2 += dz_mu
                    dh2 = dz_mu @ actor2.Wmu.T
                    dz2 = dh2 * (1 - h2**2)
                    gW2_2 += np.outer(h1, dz2)
                    gb2_2 += dz2
                    dh1 = dz2 @ actor2.W2.T
                    dz1 = dh1 * (1 - h1**2)
                    gW1_2 += np.outer(s, dz1)
                    gb1_2 += dz1
                grads2 = {"W1": gW1_2/len(batch_idx), "b1": gb1_2/len(batch_idx),
                          "W2": gW2_2/len(batch_idx), "b2": gb2_2/len(batch_idx),
                          "Wmu": gWmu_2/len(batch_idx), "bmu": gbmu_2/len(batch_idx),
                          "log_std": g_logstd2/len(batch_idx)}
                norm = np.sqrt(sum((g**2).sum() for g in grads2.values()))
                if norm > 2.0:
                    grads2 = {k: g * 2.0 / (norm + 1e-8) for k, g in grads2.items()}
                updates2 = opt2.step(grads2)
                for k, upd in updates2.items():
                    if k == "log_std":
                        actor2.log_std -= upd
                    else:
                        setattr(actor2, k, getattr(actor2, k) - upd)

                gW1_c = np.zeros_like(critic.W1); gb1_c = np.zeros_like(critic.b1)
                gW2_c = np.zeros_like(critic.W2); gb2_c = np.zeros_like(critic.b2)
                gW3_c = np.zeros_like(critic.W3); gb3_c = np.zeros_like(critic.b3)
                for i in batch_idx:
                    s1 = states1[i]; s2 = states2[i]; ret = ret1[i]
                    v = critic.forward(s1, s2)
                    err = v - ret
                    dL_dv = err
                    x = np.concatenate([s1, s2])
                    h1 = np.tanh(x @ critic.W1 + critic.b1)
                    h2 = np.tanh(h1 @ critic.W2 + critic.b2)
                    dz3 = dL_dv
                    gW3_c += np.outer(h2, [dz3])
                    gb3_c += dz3
                    dh2 = (dz3 * critic.W3.T).flatten()
                    dz2 = dh2 * (1 - h2**2)
                    gW2_c += np.outer(h1, dz2)
                    gb2_c += dz2
                    dh1 = dz2 @ critic.W2.T
                    dz1 = dh1 * (1 - h1**2)
                    gW1_c += np.outer(x, dz1)
                    gb1_c += dz1
                grads_c = {"W1": gW1_c/len(batch_idx), "b1": gb1_c/len(batch_idx),
                           "W2": gW2_c/len(batch_idx), "b2": gb2_c/len(batch_idx),
                           "W3": gW3_c/len(batch_idx), "b3": gb3_c/len(batch_idx)}
                norm = np.sqrt(sum((g**2).sum() for g in grads_c.values()))
                if norm > 2.0:
                    grads_c = {k: g * 2.0 / (norm + 1e-8) for k, g in grads_c.items()}
                updates_c = opt_c.step(grads_c)
                for k, upd in updates_c.items():
                    setattr(critic, k, getattr(critic, k) - upd)

        if (ep + 1) % 20 == 0:
            val_env = WirelessTSNEnv(cfg, K, seed + 999, max_K)
            val_rng = np.random.RandomState(seed + 777)
            f1_vals = []
            for _ in range(5):
                s1_raw = val_env.state_level1()
                s2_raw = val_env.state_level2(val_env.prev_slack)
                s1 = norm1.normalize(s1_raw)
                s2 = norm2.normalize(s2_raw)
                a1, a01_1, _ = actor1.act(s1, val_rng, deterministic=True)
                a2, a01_2, _ = actor2.act(s2, val_rng, deterministic=True)
                route_prob = a01_1.reshape(max_K, 2)[:K, 0]
                gate_priority = a01_1.reshape(max_K, 2)[:K, 1]
                airtime_frac = a01_2.reshape(max_K, 4)[:K, 0]
                order_raw = a01_2.reshape(max_K, 4)[:K, 1]
                power_frac = a01_2.reshape(max_K, 4)[:K, 2]
                retx_frac = a01_2.reshape(max_K, 4)[:K, 3]
                stats = val_env.step(route_prob, gate_priority, airtime_frac, order_raw, power_frac, retx_frac)
                f1_vals.append(stats["f1"])
            avg_f1 = np.mean(f1_vals)
            if avg_f1 > best_f1_local:
                best_f1_local = avg_f1
                best_a1 = copy.deepcopy(actor1)
                best_a2 = copy.deepcopy(actor2)
                best_c = copy.deepcopy(critic)
                print(f"    New best f1={avg_f1:.3f} at stage {stage_idx}, ep {ep+1}")
            print(f"  Stage {stage_idx}, K={K}, ep {ep+1}/{cfg.train_episodes_stage}, f1={stats['f1']:.3f}, f3={stats['f3']:.4f}, reward={reward:.2f}")

    return actor1, actor2, critic, norm1, norm2, best_f1_local, (best_a1, best_a2, best_c)


