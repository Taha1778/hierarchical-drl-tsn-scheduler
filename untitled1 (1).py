    for method in PLOT_METHODS:
        if method == "Proposed":
            r = evaluate_policy_new(cfg, cfg.K_flows, actor1, actor2, norm1, norm2, n_eval=30)
        else:
            env = WirelessTSNEnv(cfg, cfg.K_flows, seed=123, max_K=cfg.max_K)
            if method == "MAPPO-M":
                route_prob, gate_priority, airtime_frac, order_raw, power_frac, retx_frac = heuristic_MAPPO_M(cfg, env.flows, env.channel)
