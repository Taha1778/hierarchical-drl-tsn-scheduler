def generate_flows(cfg: SystemConfig, K: int, rng: np.random.RandomState) -> List[Dict]:
    counts = np.round(np.array(cfg.class_mix) * K).astype(int)
    counts[-1] = K - counts[:-1].sum()
    labels = []
    for c, n in zip(CLASSES, counts):
        labels += [c] * n
    rng.shuffle(labels)
    flows = []
    for k, c in enumerate(labels):
        if c == "TT":
            T, D, rho, rel = cfg.period_TT, cfg.deadline_TT, cfg.size_TT, cfg.reliability_TT
        elif c == "AVB":
            T, D, rho, rel = cfg.period_AVB, cfg.deadline_AVB, cfg.size_AVB, cfg.reliability_AVB
        else:
            T, D, rho, rel = cfg.period_BE, cfg.deadline_BE, cfg.size_BE, cfg.reliability_BE
        n_frames = max(1, int(round(cfg.hyperperiod / T)))
        flows.append(dict(id=k, cls=c, T=T, D=D, rho=rho * 8, eps=1 - rel, n_frames=n_frames))
    return flows


class Channel:
    def __init__(self, cfg: SystemConfig, K: int, rng: np.random.RandomState):
        self.cfg = cfg
        self.K = K
        self.rng = rng
        self.positions = None
        self.lam = None
        self.reset()

    def reset(self):
        cfg = self.cfg
        ang = self.rng.uniform(0, 2 * np.pi, self.K)
        r = np.sqrt(self.rng.uniform(0, 1, self.K)) * cfg.area_radius
        self.positions = np.column_stack([r * np.cos(ang), r * np.sin(ang)])
        self._refresh_large_scale()

    def _refresh_large_scale(self):
        cfg = self.cfg
        d = np.linalg.norm(self.positions, axis=1)
        d = np.clip(d, 0.5, None)
        PL = np.zeros_like(d)
        for i, di in enumerate(d):
            if di > cfg.d1:
                PL[i] = -cfg.C_const_dB - 35 * np.log10(di)
            elif di > cfg.d0:
                PL[i] = -cfg.C_const_dB - 15 * np.log10(cfg.d1) - 20 * np.log10(di)
            else:
                PL[i] = -cfg.C_const_dB - 15 * np.log10(cfg.d1) - 20 * np.log10(cfg.d0)
        SH = self.rng.normal(0, cfg.shadowing_std_dB, self.K)
        self.lam = 10 ** (PL / 10) * 10 ** (SH / 10)

    def sample_attempt_gain(self) -> np.ndarray:
        return self.rng.exponential(1.0, size=self.K)


def wired_latency(cfg: SystemConfig, route: np.ndarray, rho: np.ndarray,
                  gate_priority: np.ndarray) -> np.ndarray:
    hops = np.where(route == 0, cfg.hops_short, cfg.hops_long)
    base = hops * rho / cfg.R_TSN
    K = len(rho)
    queue = np.zeros(K)
    for k in range(K):
        ahead = (gate_priority > gate_priority[k]) & (route == route[k])
        queue[k] = rho[ahead].sum() / cfg.R_TSN
    return base + queue


def wireless_latency_and_failure(cfg: SystemConfig, channel: Channel, rho: np.ndarray,
                                 power: np.ndarray, retx_budget: np.ndarray,
                                 order_rank: np.ndarray, airtime_norm: np.ndarray,
                                 rng: np.random.RandomState) -> Tuple[np.ndarray, np.ndarray]:
    K = len(rho)
    B_k = cfg.bandwidth_total / K
    n0 = cfg.n0_linear
    denom = B_k * n0 + cfg.interference_floor

    max_budget = int(retx_budget.max()) if K > 0 else 0
    cum_gain = np.zeros(K)
    attempts_used = np.ones(K, dtype=int)
    success = np.zeros(K, dtype=bool)
    for attempt in range(1, max_budget + 2):
        still_trying = (~success) & (attempt <= retx_budget + 1)
        if not still_trying.any():
            break
        g_i = channel.sample_attempt_gain()
        cum_gain = np.where(still_trying, cum_gain + g_i, cum_gain)
        attempts_used = np.where(still_trying, attempt, attempts_used)
        snr_now = power * channel.lam * np.maximum(cum_gain, 1e-30) / denom
        newly_ok = still_trying & (snr_now >= cfg.gamma_star)
        success = success | newly_ok
    snr_final = power * channel.lam * np.maximum(cum_gain, 1e-30) / denom
    rate = B_k * np.log2(1 + np.maximum(snr_final, 1e-12))
    tx_time = np.ceil((rho / np.maximum(rate, 1.0)) / cfg.slot_len) * cfg.slot_len
    tx_time = np.minimum(tx_time, 0.5)
    extra_retx = np.maximum(attempts_used - 1, 0)
    retx_time = extra_retx * cfg.retx_delay

    n_t = int((airtime_norm > 1e-3).sum())
    n_t = max(n_t, 1)
    contend_global = (n_t - 1) * 0.5 * cfg.slot_len
    L_air = tx_time + retx_time + contend_global

    total_attempts = retx_budget + 1
    threshold = cfg.gamma_star * denom / np.maximum(power * channel.lam, 1e-30)
    fail_prob = special.gammainc(total_attempts, threshold)
    fail_prob = np.clip(fail_prob, 0.0, 1.0)
    return L_air, fail_prob


def evaluate_schedule(cfg: SystemConfig, flows: List[Dict], channel: Channel,
                      route_prob: np.ndarray, gate_priority: np.ndarray,
                      airtime_frac: np.ndarray, order_raw: np.ndarray,
                      power_frac: np.ndarray, retx_frac: np.ndarray,
                      rng: np.random.RandomState) -> Dict:
    K = len(flows)
    rho = np.array([f["rho"] for f in flows], dtype=float)
    D = np.array([f["D"] for f in flows])
    eps_req = np.array([f["eps"] for f in flows])
    n_frames = np.array([f["n_frames"] for f in flows])
    cls = np.array([f["cls"] for f in flows])

    route = (route_prob > 0.5).astype(int)
    L_w = wired_latency(cfg, route, rho, gate_priority)
    slack = np.maximum(0.0, D - L_w) * cfg.retx_safety_margin + 1e-9

    airtime_raw = np.clip(airtime_frac, 1e-3, 1.0)
    denom_a = airtime_raw.sum()
    airtime_norm = airtime_raw / denom_a if denom_a > 1.0 else airtime_raw
    order_rank = (-order_raw).argsort().argsort().astype(float)

    power_raw = np.clip(power_frac, 1e-3, 1.0)
    power = power_raw / power_raw.sum() * cfg.p_max

    Nmax_feasible = np.maximum(0, np.floor(slack / cfg.retx_delay)).astype(int)
    Nmax_feasible = np.minimum(Nmax_feasible, cfg.N_max)
    retx_budget = np.round(retx_frac * Nmax_feasible).astype(int)
    retx_budget = np.clip(retx_budget, 0, cfg.N_max)

    max_nf = int(n_frames.max())
    L_e2e_samples = np.zeros((K, max_nf))
    fail_samples = np.zeros((K, max_nf))
    for j in range(max_nf):
        L_air, fail_p = wireless_latency_and_failure(cfg, channel, rho, power, retx_budget,
                                                      order_rank, airtime_norm, rng)
        L_e2e = L_w + L_air + rho / cfg.R_TSN
        L_e2e_samples[:, j] = L_e2e
        fail_samples[:, j] = fail_p

    valid_mask = np.arange(max_nf)[None, :] < n_frames[:, None]
    success = (L_e2e_samples <= D[:, None]) & (fail_samples <= eps_req[:, None]) & valid_mask
    total_frames = valid_mask.sum()
    f1 = success.sum() / max(total_frames, 1)

    wC = np.array([cfg.w_class[c] for c in cls])
    wjC = np.array([cfg.wj_class[c] for c in cls])
    mean_L = np.array([L_e2e_samples[k, :n_frames[k]].mean() for k in range(K)])
    var_L = np.array([L_e2e_samples[k, :n_frames[k]].var() for k in range(K)])
    f2 = float((wC * mean_L).sum() + (wjC * var_L).sum())

    mean_fail = np.array([fail_samples[k, :n_frames[k]].mean() for k in range(K)])
    f3 = float(mean_fail.mean())

    f4 = float(power.sum() + cfg.beta_retx * (retx_budget * cfg.retx_delay).sum())

    lat_viol = ((L_e2e_samples > D[:, None]) & valid_mask).sum() / max(total_frames, 1)
    rel_viol = ((fail_samples > eps_req[:, None]) & valid_mask).sum() / max(total_frames, 1)
    throughput = (success * rho[:, None]).sum() / cfg.hyperperiod

    return dict(f1=f1, f2=f2, f3=f3, f4=f4, failure_rate=1 - f1,
                latency_violation=lat_viol, reliability_violation=rel_viol,
                throughput=throughput, mean_latency=float(mean_L.mean()),
                mean_reliability_fail=f3, slack=slack, L_w=L_w,
                airtime_norm=airtime_norm, power=power, retx_budget=retx_budget)


def build_state_level1_padded(cfg: SystemConfig, flows: List[Dict],
                              prev_gate_priority: np.ndarray, max_K: int) -> np.ndarray:
    K = len(flows)
    if K == 0:
        return np.zeros(max_K * 6)
    D = np.array([f["D"] for f in flows])
    rho = np.array([f["rho"] for f in flows], dtype=float)
    cls_onehot = np.zeros((K, 3))
    for i, f in enumerate(flows):
        cls_onehot[i, CLASSES.index(f["cls"])] = 1.0
    D_norm = D / D.max()
    rho_norm = rho / rho.max()
    feats = np.column_stack([cls_onehot, D_norm, rho_norm, prev_gate_priority])
    pad = max_K - K
    if pad > 0:
        feats = np.vstack([feats, np.zeros((pad, 6))])
    return feats.flatten()


def build_state_level2_padded(cfg: SystemConfig, flows: List[Dict], channel: Channel,
                              slack: np.ndarray, prev_power: np.ndarray,
                              prev_retx: np.ndarray, prev_airtime: np.ndarray,
                              max_K: int) -> np.ndarray:
    K = len(flows)
    if K == 0:
        return np.zeros(max_K * 6)
    lam_norm = (channel.lam - channel.lam.min()) / (channel.lam.max() - channel.lam.min() + 1e-12)
    slack_norm = slack / max(slack.max(), 1e-9)
    contend_proxy = np.full(K, K / cfg.K_flows)
    feats = np.column_stack([lam_norm, slack_norm, prev_power, prev_retx, prev_airtime, contend_proxy])
    pad = max_K - K
    if pad > 0:
        feats = np.vstack([feats, np.zeros((pad, 6))])
    return feats.flatten()


