def uniform_init(shape, scale=0.01):
    fan_in = shape[0]
    bound = scale / np.sqrt(fan_in)
    return np.random.uniform(-bound, bound, shape)


class RunningNorm:
    def __init__(self, shape):
        self.mean = np.zeros(shape)
        self.var = np.ones(shape)
        self.count = 0

    def update(self, x):
        if x.ndim == 1:
            x = x.reshape(1, -1)
        batch_mean = x.mean(axis=0)
        batch_var = x.var(axis=0)
        batch_count = x.shape[0]
        new_count = self.count + batch_count
        delta = batch_mean - self.mean
        self.mean = self.mean + delta * batch_count / new_count
        m_a = self.var * self.count
        m_b = batch_var * batch_count
        M2 = m_a + m_b + delta ** 2 * self.count * batch_count / new_count
        self.var = M2 / new_count
        self.count = new_count

    def normalize(self, x):
        if self.count < 2:
            return x
        return (x - self.mean) / np.sqrt(self.var + 1e-8)


class Actor:
    def __init__(self, state_dim, action_dim, hidden=256, seed=0):
        rng = np.random.RandomState(seed)
        self.W1 = uniform_init((state_dim, hidden), 1.0)
        self.b1 = np.zeros(hidden)
        self.W2 = uniform_init((hidden, hidden), 1.0)
        self.b2 = np.zeros(hidden)
        self.Wmu = uniform_init((hidden, action_dim), 0.01)
        self.bmu = np.zeros(action_dim)
        self.log_std = np.full(action_dim, -0.3)
        self.lr = 3e-4

    def forward(self, s):
        h1 = np.tanh(s @ self.W1 + self.b1)
        h2 = np.tanh(h1 @ self.W2 + self.b2)
        mu = np.tanh(h2 @ self.Wmu + self.bmu)
        return mu, h2

    def act(self, s, rng, deterministic=False):
        mu, _ = self.forward(s)
        std = np.exp(self.log_std)
        if deterministic:
            a = mu
        else:
            a = mu + std * rng.normal(size=mu.shape)
        a = np.clip(a, -0.999, 0.999)
        logp = (-0.5 * ((a - mu) / std) ** 2 - np.log(std) - 0.5 * np.log(2 * np.pi)).sum()
        a01 = (a + 1) / 2
        return a, a01, logp


class Critic:
    def __init__(self, state_dim1, state_dim2, hidden=256, seed=0):
        total_dim = state_dim1 + state_dim2
        rng = np.random.RandomState(seed)
        self.W1 = uniform_init((total_dim, hidden), 1.0)
        self.b1 = np.zeros(hidden)
        self.W2 = uniform_init((hidden, hidden), 1.0)
        self.b2 = np.zeros(hidden)
        self.W3 = uniform_init((hidden, 1), 0.01)
        self.b3 = np.zeros(1)

    def forward(self, s1, s2):
        x = np.concatenate([s1, s2])
        h1 = np.tanh(x @ self.W1 + self.b1)
        h2 = np.tanh(h1 @ self.W2 + self.b2)
        v = (h2 @ self.W3 + self.b3)[0]
        return v


class Adam:
    def __init__(self, params, lr):
        self.lr = lr
        self.m = {k: np.zeros_like(v) for k, v in params.items()}
        self.v = {k: np.zeros_like(v) for k, v in params.items()}
        self.t = 0
        self.b1, self.b2, self.eps = 0.9, 0.999, 1e-8

    def step(self, grads):
        self.t += 1
        updates = {}
        for k, g in grads.items():
            self.m[k] = self.b1 * self.m[k] + (1 - self.b1) * g
            self.v[k] = self.b2 * self.v[k] + (1 - self.b2) * (g * g)
            mhat = self.m[k] / (1 - self.b1 ** self.t)
            vhat = self.v[k] / (1 - self.b2 ** self.t)
            updates[k] = self.lr * mhat / (np.sqrt(vhat) + self.eps)
        return updates


def compute_gae(rewards, values, gamma, lam):
    T = len(rewards)
    values = np.array(values + [values[-1]])
    adv = np.zeros(T)
    last = 0.0
    for t in reversed(range(T)):
        delta = rewards[t] + gamma * values[t+1] - values[t]
        last = delta + gamma * lam * last
        adv[t] = last
    returns = adv + values[:-1]
    return adv, returns


class WirelessTSNEnv:
    def __init__(self, cfg: SystemConfig, K: int, seed: int, max_K: int):
        self.cfg = cfg
        self.K = K
        self.max_K = max_K
        self.rng = np.random.RandomState(seed)
        self.flows = generate_flows(cfg, K, self.rng)
        self.channel = Channel(cfg, K, self.rng)
        self.prev_gate_priority = np.full(K, 0.5)
        self.prev_power = np.full(K, 1.0 / K) if K > 0 else np.array([])
        self.prev_retx = np.zeros(K)
        self.prev_airtime = np.full(K, 1.0 / K) if K > 0 else np.array([])
        self.prev_slack = np.zeros(K) if K > 0 else np.array([])

    def state_level1(self):
        return build_state_level1_padded(self.cfg, self.flows,
                                         self.prev_gate_priority, self.max_K)

    def state_level2(self, slack: np.ndarray):
        return build_state_level2_padded(self.cfg, self.flows, self.channel, slack,
                                         self.prev_power, self.prev_retx,
                                         self.prev_airtime, self.max_K)

    def step(self, route_prob, gate_priority, airtime_frac, order_raw, power_frac, retx_frac):
        stats = evaluate_schedule(self.cfg, self.flows, self.channel,
                                  route_prob[:self.K], gate_priority[:self.K],
                                  airtime_frac[:self.K], order_raw[:self.K],
                                  power_frac[:self.K], retx_frac[:self.K],
                                  self.rng)
        self.prev_gate_priority = gate_priority[:self.K]
        if self.K > 0:
            self.prev_power = stats["power"] / (stats["power"].sum() + 1e-9)
            self.prev_retx = retx_frac[:self.K]
            self.prev_airtime = stats["airtime_norm"]
            self.prev_slack = stats["slack"]
        self.channel.positions += self.rng.normal(0, 0.5, self.channel.positions.shape)
        self.channel.positions = np.clip(self.channel.positions, -self.cfg.area_radius, self.cfg.area_radius)
        self.channel._refresh_large_scale()
        return stats


