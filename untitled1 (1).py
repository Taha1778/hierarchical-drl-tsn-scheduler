def evaluate_policy_new(cfg: SystemConfig, K: int, actor1: Actor, actor2: Actor,
                        norm1: RunningNorm, norm2: RunningNorm,
                        n_eval: int = 50, seed: int = 999) -> Dict:
    rng = np.random.RandomState(seed)
    env = WirelessTSNEnv(cfg, K, seed, cfg.max_K)
    agg = {"f1": [], "f2": [], "f3": [], "f4": [], "failure_rate": [],
           "latency_violation": [], "reliability_violation": [], "throughput": [],
           "mean_latency": []}
    t0 = time.time()
    for _ in range(n_eval):
        s1_raw = env.state_level1()
        s2_raw = env.state_level2(env.prev_slack)
        s1 = norm1.normalize(s1_raw)
        s2 = norm2.normalize(s2_raw)
        a1, a01_1, _ = actor1.act(s1, rng, deterministic=True)
        a2, a01_2, _ = actor2.act(s2, rng, deterministic=True)
        K_actual = K
        max_K = cfg.max_K
        route_prob = a01_1.reshape(max_K, 2)[:K_actual, 0]
        gate_priority = a01_1.reshape(max_K, 2)[:K_actual, 1]
        airtime_frac = a01_2.reshape(max_K, 4)[:K_actual, 0]
        order_raw = a01_2.reshape(max_K, 4)[:K_actual, 1]
        power_frac = a01_2.reshape(max_K, 4)[:K_actual, 2]
        retx_frac = a01_2.reshape(max_K, 4)[:K_actual, 3]
        stats = env.step(route_prob, gate_priority, airtime_frac, order_raw, power_frac, retx_frac)
        for kk in agg:
            agg[kk].append(stats[kk])
    elapsed_ms = (time.time() - t0) * 1000.0 / n_eval
    out = {kk: float(np.mean(v)) for kk, v in agg.items()}
    out["compute_ms"] = elapsed_ms
    out["failure_rate"] = max(out["failure_rate"], 1e-5)
    out["reliability_violation"] = max(out["reliability_violation"], 1e-5)
    out["latency_violation"] = max(out["latency_violation"], 1e-5)
    return out


